import { brand, createTheme, DEFAULT_ACCENT, font, radius, toCssVariables, type Theme } from '@shikshit/shared/tokens';

/**
 * Renders src/styles/tokens.css from @shikshit/shared so web and mobile can never disagree about a colour.
 * Run `npm run tokens:gen` after bumping @shikshit/shared; `npm test` fails if the file is stale.
 *
 *  - :root / [data-theme='dark'] carry the mode-dependent colour variables (default accent). ThemeProvider overrides
 *    the accent-dependent ones at runtime for institutes with their own brand colour.
 *  - @theme inline gives Tailwind short utility names (bg-canvas, text-fg, border-line, bg-accent, text-danger…).
 *  - @theme holds the static scales (radius, font sizes, families).
 */
const modeVars = (theme: Theme): string =>
  Object.entries(toCssVariables(theme))
    .filter(([k]) => k.startsWith('--color-') || k.startsWith('--shadow-'))
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n');

const ALIASES: Record<string, string> = {
  canvas: 'bg-canvas',
  surface: 'bg-surface',
  raised: 'bg-raised',
  subtle: 'bg-subtle',
  inverse: 'bg-inverse',
  overlay: 'bg-overlay',
  fg: 'text-primary',
  'fg-muted': 'text-secondary',
  'fg-subtle': 'text-tertiary',
  'fg-inverse': 'text-inverse',
  'on-accent': 'text-on-accent',
  link: 'text-link',
  line: 'border-default',
  'line-subtle': 'border-subtle',
  'line-strong': 'border-strong',
  accent: 'accent-default',
  'accent-hover': 'accent-hover',
  'accent-active': 'accent-active',
  'accent-subtle': 'accent-subtle',
  'accent-fg': 'accent-text',
  ring: 'focus-ring',
};
const STATUSES = ['success', 'warning', 'danger', 'info'] as const;

export function renderTokensCss(): string {
  const light = createTheme('light', DEFAULT_ACCENT);
  const dark = createTheme('dark', DEFAULT_ACCENT);
  const aliases = [
    ...Object.entries(ALIASES).map(([name, target]) => `  --color-${name}: var(--color-${target});`),
    ...STATUSES.flatMap((s) => [
      `  --color-${s}: var(--color-status-${s}-fg);`,
      `  --color-${s}-bg: var(--color-status-${s}-bg);`,
      `  --color-${s}-line: var(--color-status-${s}-border);`,
    ]),
    // brand colours are the same in both modes: the ink of brand panels and the gold of rules and marks
    `  --color-brand-ink: ${brand.ink};`,
    `  --color-brand-ink-deep: ${brand.inkDeep};`,
    `  --color-brand-gold: ${brand.gold};`,
    `  --color-brand-gold-soft: ${brand.goldSoft};`,
    `  --color-white: #FFFFFF;`,
    `  --color-transparent: transparent;`,
    // shadows follow the mode; distinct names so they never refer to themselves
    `  --shadow-soft: var(--shadow-sm);`,
    `  --shadow-card: var(--shadow-md);`,
    `  --shadow-float: var(--shadow-lg);`,
  ].join('\n');
  const radii = Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v}px;`).join('\n');
  const sizes = Object.entries(font.size)
    .map(([k, v]) => `  --text-${k}: ${v}px;\n  --text-${k}--line-height: ${font.lineHeight[k as keyof typeof font.lineHeight]}px;`)
    .join('\n');

  return `/* GENERATED by scripts/gen-tokens-css.ts from @shikshit/shared. Do not edit; run \`npm run tokens:gen\`. */

:root {
${modeVars(light)}
}

[data-theme='dark'] {
${modeVars(dark)}
}

@theme inline {
  --color-*: initial;
${aliases}
}

@theme {
${radii}
${sizes}
  --font-sans: ${font.family.sans};
  --font-mono: ${font.family.mono};
  --font-display: ${font.family.display};
}
`;
}
